"""Build assets/ambient/zones.min.js: IANA time zone -> approximate [lat, lon] of its principal city.

ambient.js uses it to place a visitor without asking for permission: the browser reports its time
zone (Intl.DateTimeFormat().resolvedOptions().timeZone), and the zone's principal city decides the
sun's elevation (time-of-day phase) and where the current weather is read.

Inputs (public domain, download both into one directory first):
  https://raw.githubusercontent.com/eggert/tz/main/zone.tab   zone -> ISO 6709 coordinates
  https://raw.githubusercontent.com/eggert/tz/main/backward   legacy names (e.g. Asia/Calcutta -> Asia/Kolkata)

Usage: python3 -I bin/build_zones.py <dir with zone.tab and backward> assets/ambient/zones.min.js

Output: window.AMB_ZONES = {"z": {zone: [lat, lon]}, "a": {legacyName: zone}}, degrees rounded
to 0.1 (north- and east-positive). Lookup is z[tz] || z[a[tz]].
"""

import json
import os
import re
import sys


def iso6709(coord: str) -> tuple:
    """'+DDMM+DDDMM' or '+DDMMSS+DDDMMSS' -> (lat, lon) in degrees, rounded to 0.1."""
    m = re.match(r"([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$", coord)
    if not m:
        raise ValueError(f"bad ISO 6709 coordinate: {coord!r}")
    sa, d1, m1, s1, so, d2, m2, s2 = m.groups()
    lat = int(d1) + int(m1) / 60 + int(s1 or 0) / 3600
    lon = int(d2) + int(m2) / 60 + int(s2 or 0) / 3600
    return round(lat if sa == "+" else -lat, 1), round(lon if so == "+" else -lon, 1)


def main(raw: str, out: str) -> int:
    zones = {}
    with open(os.path.join(raw, "zone.tab"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            _cc, coord, name = line.split("\t")[:3]
            zones[name.strip()] = list(iso6709(coord))
    aliases = {}
    with open(os.path.join(raw, "backward"), encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            # "Link TARGET LINK-NAME"; keep links whose target is a zone.tab principal zone
            if len(parts) >= 3 and parts[0] == "Link" and parts[1] in zones:
                aliases[parts[2]] = parts[1]
    header = (
        "/* IANA tz zone.tab + backward (public domain): zone -> [lat, lon] of its principal city."
        " Generated by bin/build_zones.py. */\n"
    )
    body = "window.AMB_ZONES=" + json.dumps({"z": zones, "a": aliases}, separators=(",", ":")) + ";\n"
    with open(out, "w", encoding="utf-8") as f:
        f.write(header + body)
    print(f"zones={len(zones)} aliases={len(aliases)} bytes={len((header + body).encode())}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__.strip().splitlines()[-4], file=sys.stderr)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
